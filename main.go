package main

import (
	"log"
	"share-cat/Nepeta-cataria/boot"
	"share-cat/Nepeta-cataria/config"
	"share-cat/Nepeta-cataria/global"
	"share-cat/Nepeta-cataria/models"
	"share-cat/Nepeta-cataria/routes"

	_ "share-cat/Nepeta-cataria/docs" // docs is generated by Swag CLI, you have to import it.

	"github.com/gin-contrib/cors"
	"github.com/gin-gonic/gin"
	_ "github.com/joho/godotenv/autoload"
)

// @title           Share Cat Nepeta Cataria API
// @version         1.0
// @description     Share Cat Nepeta Cataria API Documentation

// @securitydefinitions.bearerauth jwt
func main() {
	initdb()
	err := boot.Initfile()
	if err != nil {
		log.Fatal("failed to create judges directory")
		log.Fatal(err)
	}
	server := gin.Default()
	corsConfig := cors.DefaultConfig()
	corsConfig.AllowAllOrigins = true
	server.Use(gin.Logger())
	server.Use(cors.New(corsConfig))

	app := boot.NewApplication(global.DB)
	routes.SetupRouter(server, global.DB, app.Controllers)

	server.Run()

}

func initdb() {
	var err error
	DBsetting := config.GetConfig()
	global.DB, err = boot.NewDBEngine(&DBsetting.DatabaseSetting)

	if err != nil {
		log.Fatal("failed to connect database")
		log.Fatal(err)
	}

	dbInit()
}

func dbInit() {
	err := global.DB.AutoMigrate(
		&models.Achievement{},
		&models.ChatSession{},
		&models.Discussion{},
		&models.Judge{},
		&models.Permission{},
		&models.School{},
		&models.Social{},
		&models.Solution{},
		&models.SubmitEffect{},
		&models.SupportLang{},
		&models.SystemConfig{},
		&models.User{},
		&models.UserProfile{},
		&models.RpgProfile{},
	)
	if err != nil {
		log.Fatal(err)
	}

}
